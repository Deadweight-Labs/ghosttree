func TestClassifyPromptSeparatesTypedFromInjected(t *testing.T) {
	for _, c := range []struct {
		text, label string
		typed       bool
	}{
		{"wann haben wir den Wagen repariert?", "prompt", true},
		{"  fix the login page  ", "prompt", true},
		{"<task-notification>\n<task-id>x</task-id></task-notification>", "tag:task-notification", false},
		{"<bash-input>ls</bash-input>", "tag:bash-input", false},
		{"<bash-stdout>ok</bash-stdout>", "tag:bash-stdout", false},
		{"<system-reminder>x</system-reminder>", "tag:system-reminder", false},
		{"[Request interrupted by user]", "interrupt", false},
		{"[Request interrupted by user for tool use]", "interrupt", false},
		{"This session is being continued from a previous conversation that ran out of context.", "compaction-summary", false},
		{"Caveat: The messages below were generated by the user while running local commands.", "caveat", false},
		{"[SYSTEM NOTIFICATION: a job finished]", "system-notification", false},
		{"Stop hook feedback: keep going", "hook-feedback", false},
		{"", "empty", false},
		{"   \n ", "empty", false},
		// A tag that no harness injects is pasted markup: it counts as typed.
		{"<svg width=\"10\"></svg> what is this?", "unknown-tag:svg", true},
		{"<pasted_content>some log</pasted_content>", "unknown-tag:pasted_content", true},
		// A tag that does not lead the text does not matter.
		{"look at <task-notification> in the log", "prompt", true},
	} {
		got := ClassifyPrompt(c.text)
		if got != c.label {
			t.Errorf("%q: label %q, want %q", c.text, got, c.label)
		}
		if TypedPrompt(got) != c.typed {
			t.Errorf("%q: typed = %v, want %v", c.text, TypedPrompt(got), c.typed)
		}
	}
}

func row(seq int, role string, prompt bool, tools int, text string) TurnRow {
	return TurnRow{Chunk: int64(1000 + seq), Seq: seq, Role: role, Prompt: prompt, ToolCalls: tools, Text: text}
}

func describe(ps []Picked) string {
	var out []string
	for _, p := range ps {
		open := ""
		if p.Open {
			open = "*"
		}
		out = append(out, fmt.Sprintf("%d:%s:t%d%s", p.Seq, p.Part, p.Turn, open))
	}
	return strings.Join(out, " ")
}

func TestPickTurnTextsTakesPromptsAndTheLastAnswerOfEachTurn(t *testing.T) {
	rows := []TurnRow{
		row(0, "user", true, 0, "please look into the cache layer for me"),
		row(1, "assistant", false, 0, "I will start by reading the code"),
		row(2, "", false, 1, ""), // a tool call
		row(3, "assistant", false, 0, "the cache is keyed by path"),
		row(4, "", false, 2, ""),
		row(5, "assistant", false, 0, "so the answer is: keys are paths"),
		row(6, "user", true, 0, "and how long do entries live?"),
		row(7, "assistant", false, 0, "ten minutes"),
	}
	got := PickTurnTexts(rows)
	if want := "0:prompt:t0 5:final:t0 6:prompt:t1 7:final:t1*"; describe(got) != want {
		t.Fatalf("picked %s, want %s", describe(got), want)
	}
	if got[1].Text != "so the answer is: keys are paths" || got[1].Chunk != 1005 {
		t.Fatalf("the answer carries its row: %+v", got[1])
	}
}

func TestPickTurnTextsIgnoresInjectedPromptsAndKeepsTheTurnOpen(t *testing.T) {
	rows := []TurnRow{
		row(0, "user", true, 0, "build the report"),
		row(1, "assistant", false, 0, "started the build in the background"),
		// A background job reports: not a prompt, the turn goes on.
		row(2, "user", true, 0, "<task-notification>\n<task-id>b1</task-id>\n</task-notification>"),
		row(3, "assistant", false, 0, "the build is done, the report is in out/"),
		row(4, "user", true, 0, "[Request interrupted by user]"),
		row(5, "user", true, 0, "This session is being continued from a previous conversation that ran out of context."),
		row(6, "user", true, 0, "<bash-input>ls</bash-input>"),
		row(7, "user", true, 0, "thanks, now the second one"),
		row(8, "assistant", false, 0, "second one is done"),
	}
	got := PickTurnTexts(rows)
	if want := "0:prompt:t0 3:final:t0 7:prompt:t1 8:final:t1*"; describe(got) != want {
		t.Fatalf("picked %s, want %s", describe(got), want)
	}
}

func TestPickTurnTextsAnswersBeforeTheFirstPromptAreATurnOfTheirOwn(t *testing.T) {
	rows := []TurnRow{
		row(0, "assistant", false, 0, "resuming where we stopped"),
		row(1, "user", true, 0, "go on with the migration"),
	}
	got := PickTurnTexts(rows)
	if want := "0:final:t0 1:prompt:t1"; describe(got) != want {
		t.Fatalf("picked %s, want %s", describe(got), want)
	}
	// The only turn of a session is open while it has an answer.
	if only := PickTurnTexts(rows[:1]); describe(only) != "0:final:t0*" {
		t.Fatalf("a session with one answer: %s", describe(only))
	}
}

func TestPickTurnTextsOpenIsOnlyTheAnswerOfTheLastTurn(t *testing.T) {
	rows := []TurnRow{
		row(0, "user", true, 0, "first question here"),
		row(1, "assistant", false, 0, "first answer"),
		row(2, "user", true, 0, "second question here"),
	}
	got := PickTurnTexts(rows)
	if want := "0:prompt:t0 1:final:t0 2:prompt:t1"; describe(got) != want {
		t.Fatalf("picked %s, want %s", describe(got), want)
	}
	for _, p := range got {
		if p.Open {
			t.Fatalf("no answer is open: the first is closed by the second prompt, the second turn has none: %+v", p)
		}
	}
}

func TestPickTurnTextsNeedsNoOrderAndEmptyInputIsNothing(t *testing.T) {
	rows := []TurnRow{
		row(3, "assistant", false, 0, "the answer"),
		row(0, "user", true, 0, "the question"),
		row(2, "", false, 1, ""),
	}
	if got := describe(PickTurnTexts(rows)); got != "0:prompt:t0 3:final:t0*" {
		t.Fatalf("%s", got)
	}
	if !slices.Equal(rows[0:1], []TurnRow{row(3, "assistant", false, 0, "the answer")}) {
		t.Fatal("the caller's rows were reordered")
	}
	if len(PickTurnTexts(nil)) != 0 {
		t.Fatal("nothing in, nothing out")
	}
	// Tool calls alone are no text.
	if len(PickTurnTexts([]TurnRow{row(0, "", false, 3, "")})) != 0 {
		t.Fatal("a call is no text")
	}
}
