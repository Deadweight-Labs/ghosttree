func numbered(prefix string, n int) string {
	var b strings.Builder
	b.WriteString("package x\n\n")
	for i := 1; i <= n; i++ {
		fmt.Fprintf(&b, "// %s %d\nfunc F%d() {}\n", prefix, i, i)
	}
	return b.String()
}

// ghostFixture is a checkout in which every state of a description occurs.
type ghostFixture struct {
	repo      *Repo
	dir       string
	described map[string]store.GhostFile
}

func describeAs(t *testing.T, dir, rel, text string) store.GhostFile {
	t.Helper()
	sha, blob, lines, err := ghost.HashFile(filepath.Join(dir, filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return store.GhostFile{Path: rel, Kind: "file", Description: text, ContentSHA: sha, GitBlob: blob, LineCount: lines}
}

const oldText = "Beschreibt, was die Datei tut, und welche Invarianten gelten. Wird beim Start gelesen."

func newGhostFixture(t *testing.T) ghostFixture {
	t.Helper()
	dir := t.TempDir()
	gitIn(t, dir, "init", "-q", "-b", "main")
	fx := ghostFixture{dir: dir, described: map[string]store.GhostFile{}}
	// Versions of the files at the time they were described.
	writeIn(t, dir, "internal/store/stale.go", numbered("alt", 10))
	writeIn(t, dir, "internal/store/drift.go", numbered("gleich", 20))
	writeIn(t, dir, "internal/store/fresh.go", numbered("frisch", 5))
	for _, f := range []string{"stale.go", "drift.go", "fresh.go"} {
		fx.described["internal/store/"+f] = describeAs(t, dir, "internal/store/"+f, oldText)
	}
	gitIn(t, dir, "add", ".")
	gitIn(t, dir, "commit", "-q", "-m", "start")
	// Since then: stale.go was rewritten, drift.go changed in one place.
	writeIn(t, dir, "internal/store/stale.go", numbered("neu", 10))
	writeIn(t, dir, "internal/store/drift.go", strings.Replace(numbered("gleich", 20), "// gleich 3", "// geändert 3", 1))
	// Files with no description.
	writeIn(t, dir, "cmd/a.go", numbered("a", 3))
	writeIn(t, dir, "internal/web/z.go", numbered("z", 3))
	writeIn(t, dir, "README.md", "# Projekt\n\nEine Datei ohne Beschreibung.\n")
	// Files that need none.
	writeIn(t, dir, "go.sum", "x v1 h1:abc\n")
	writeIn(t, dir, "internal/store/testdata/case.txt", "daten\n")
	writeIn(t, dir, "internal/store/stale_test.go", "package store\n")
	writeIn(t, dir, "assets/logo.png", "\x89PNG kein echtes Bild\n")
	writeIn(t, dir, "LICENSE", "Lizenz\n")
	writeIn(t, dir, "docs/mit Leerzeichen.md", "# Ein Pfad, den die Aufzeichnung der Session nicht von path:line trennen kann\n")
	writeIn(t, dir, "gen/api.go", "// Code generated by tool. DO NOT EDIT.\npackage gen\n")
	writeIn(t, dir, "data/blob.dat", "ab\x00cd\n")
	writeIn(t, dir, "big.txt", strings.Repeat("zeile\n", maxGhostFileBytes/5))
	writeIn(t, dir, "empty-by-review.go", numbered("r", 2))
	gitIn(t, dir, "add", ".")
	gitIn(t, dir, "commit", "-q", "-m", "weiter")
	if err := os.Symlink("/etc/hostname", filepath.Join(dir, "link.go")); err == nil {
		gitIn(t, dir, "add", "link.go")
		gitIn(t, dir, "commit", "-q", "-m", "link")
	}
	repo, err := OpenRepo(dir)
	if err != nil {
		t.Fatal(err)
	}
	fx.repo = repo
	return fx
}

func paths(gs []GhostPath) string {
	var ps []string
	for _, g := range gs {
		ps = append(ps, g.Path)
	}
	return strings.Join(ps, " ")
}

func TestGhostSelectionTakesStaleBeforeUndescribedBeforeDriftedAndSkipsWhatNeedsNoDescription(t *testing.T) {
	fx := newGhostFixture(t)
	reviewed := map[string]bool{"empty-by-review.go": true}
	got, rot := SelectGhosts(fx.repo, fx.described, reviewed, nil, nil, 0)
	want := "internal/store/stale.go README.md cmd/a.go internal/web/z.go internal/store/drift.go"
	if paths(got) != want {
		t.Fatalf("order = %s\nwant    %s", paths(got), want)
	}
	byPath := map[string]GhostPath{}
	for _, g := range got {
		byPath[g.Path] = g
	}
	if s := byPath["internal/store/stale.go"]; s.State != GhostStale || s.Percent <= 25 || s.Old != oldText || s.Blob == "" || s.SHA == "" || s.Lines == 0 {
		t.Errorf("stale = %+v", s)
	}
	if d := byPath["internal/store/drift.go"]; d.State != GhostDrifted || d.Percent == 0 || d.Percent > 25 {
		t.Errorf("drifted = %+v", d)
	}
	if u := byPath["cmd/a.go"]; u.State != GhostUndescribed || u.Old != "" || u.SHA == "" {
		t.Errorf("undescribed = %+v", u)
	}
	if rot.Fresh != 1 || rot.Reviewed != 1 || rot.Due != 5 || rot.Skipped < 6 {
		t.Errorf("rotation = %+v", rot)
	}
	for _, g := range got {
		if IsGhostSkipped(g.Path) {
			t.Errorf("%s was chosen although it needs no description", g.Path)
		}
	}
	for _, skipped := range []string{"go.sum", "internal/store/testdata/case.txt", "internal/store/stale_test.go", "assets/logo.png", "LICENSE", "docs/mit Leerzeichen.md", "gen/api.go", "data/blob.dat", "big.txt", "link.go"} {
		if strings.Contains(" "+paths(got)+" ", " "+skipped+" ") {
			t.Errorf("%s was chosen", skipped)
		}
	}
	// The limit keeps the most urgent ones.
	if limited, _ := SelectGhosts(fx.repo, fx.described, reviewed, nil, nil, 2); paths(limited) != "internal/store/stale.go README.md" {
		t.Errorf("limit 2 = %s", paths(limited))
	}
}

func TestGhostSelectionLeavesOutWhatWasLookedAtAndWhatHasAProposalStanding(t *testing.T) {
	fx := newGhostFixture(t)
	all, _ := SelectGhosts(fx.repo, fx.described, nil, nil, nil, 0)
	stale := all[0]
	// The gardener looked at the stale file in this state (and said the description holds).
	seen := map[int64]Seen{GhostKey(stale.Path): {EntryHash: stale.Stamp(), Verdict: "kept"}}
	got, rot := SelectGhosts(fx.repo, fx.described, nil, seen, nil, 0)
	if strings.Contains(paths(got), stale.Path) || rot.Looked != 1 {
		t.Errorf("a path looked at in its present state came back: %s (%+v)", paths(got), rot)
	}
	// The same path in another state is asked again: the file changed.
	seen[GhostKey(stale.Path)] = Seen{EntryHash: "anderer Stand"}
	if got, _ := SelectGhosts(fx.repo, fx.described, nil, seen, nil, 0); !strings.Contains(paths(got), stale.Path) {
		t.Error("a path whose state changed was not asked again")
	}
	// A proposal of the gardener for this version of the file stands, in any state.
	note := GhostProposal("github.com/o/r", GhostProposalData{GhostPath: stale, Description: strings.Repeat("Text. ", 12)})
	note.Status = "deprecated"
	got, rot = SelectGhosts(fx.repo, fx.described, nil, nil, []store.Knowledge{note}, 0)
	if strings.Contains(paths(got), stale.Path) || rot.Proposed != 1 {
		t.Errorf("a path with a rejected proposal came back: %s (%+v)", paths(got), rot)
	}
	// Once the file changed, the proposal is about another version.
	moved := stale
	moved.Blob = strings.Repeat("a", 40)
	if GhostProposed([]store.Knowledge{note}, stale.Path, moved.Blob) {
		t.Error("a proposal stood for a version of the file it was not written for")
	}
	other := note
	other.Harness = "mcp"
	if GhostProposed([]store.Knowledge{other}, stale.Path, stale.Blob) {
		t.Error("a note that is not the gardener's counted as its proposal")
	}
}

func TestGhostChunksKeepFilesOfADirectoryTogetherAndEven(t *testing.T) {
	var gs []GhostPath
	for _, p := range []string{"b/2.go", "a/1.go", "b/1.go", "a/2.go", "c/1.go", "a/3.go", "c/2.go", "b/3.go", "a/4.go"} {
		gs = append(gs, GhostPath{Path: p})
	}
	chunks := ChunkGhosts(gs, 8)
	if len(chunks) != 2 || len(chunks[0]) != 4 || len(chunks[1]) != 5 {
		t.Fatalf("9 files at 8 per session: %d chunks of %d and %d", len(chunks), len(chunks[0]), len(chunks[1]))
	}
	if paths(chunks[0]) != "a/1.go a/2.go a/3.go a/4.go" {
		t.Errorf("first chunk = %s", paths(chunks[0]))
	}
	if ChunkGhosts(nil, 8) != nil {
		t.Error("no files, no chunks")
	}
}

func ghostJSON(items ...string) string { return `{"ghosts":[` + strings.Join(items, ",") + `]}` }

func ghostItem(path, verdict, desc string) string {
	b, _ := json.Marshal(map[string]string{"path": path, "verdict": verdict, "description": desc, "reason": "weil es sich geändert hat"})
	return string(b)
}

const goodText = "Hält den Zustand des Dienstes. Invariante: genau ein Schreiber. Hängt mit store/writer.go zusammen."

func TestGhostAnswerIsHeldToTheFileTheSessionReadAndToTheTextBounds(t *testing.T) {
	fx := newGhostFixture(t)
	pkg, _ := SelectGhosts(fx.repo, fx.described, nil, nil, nil, 0)
	want := map[string]GhostPath{}
	for _, g := range pkg {
		want[g.Path] = g
	}
	read := func(ps ...string) *Looked { return seenBy(ps) }
	cases := []struct {
		name   string
		answer string
		looked *Looked
		ok     bool
		kept   bool
		why    string
	}{
		{"a description", ghostItem("cmd/a.go", "describe", goodText), read("cmd/a.go"), true, false, ""},
		{"a path with a leading ./", ghostItem("./cmd/a.go", "describe", goodText), read("cmd/a.go"), true, false, ""},
		{"a file a search only listed", ghostItem("cmd/a.go", "describe", goodText), seenBy(nil, "cmd/a.go"), false, false, "nicht gelesen"},
		{"a path that is not in the package", ghostItem("cmd/b.go", "describe", goodText), read("cmd/b.go"), false, false, "nicht im Paket"},
		{"a file the session did not read", ghostItem("cmd/a.go", "describe", goodText), read(), false, false, "nicht gelesen"},
		{"an empty text", ghostItem("cmd/a.go", "describe", "  \n "), read("cmd/a.go"), false, false, "leerer Text"},
		{"a text that says nothing", ghostItem("cmd/a.go", "describe", "Tut etwas."), read("cmd/a.go"), false, false, "zu kurz"},
		{"a document", ghostItem("cmd/a.go", "describe", strings.Repeat("Wort ", 800)), read("cmd/a.go"), false, false, "zu lang"},
		{"control characters", ghostItem("cmd/a.go", "describe", goodText+"\x00"), read("cmd/a.go"), false, false, "Steuerzeichen"},
		{"a right-to-left override", ghostItem("cmd/a.go", "describe", goodText+"\u202e"), read("cmd/a.go"), false, false, "Steuerzeichen"},
		{"the old text again says keep", ghostItem("internal/store/stale.go", "describe", oldText+" Noch ein Satz, damit es lang genug ist."), read("internal/store/stale.go"), true, false, ""},
		{"keep", ghostItem("internal/store/stale.go", "keep", ""), read(), false, true, ""},
		{"an unknown verdict", ghostItem("cmd/a.go", "rewrite", goodText), read("cmd/a.go"), false, false, "unbekanntes Urteil"},
	}
	for _, c := range cases {
		v, err := validateGhosts(fx.repo, ghostJSON(c.answer), pkg, c.looked)
		if err != nil {
			t.Fatalf("%s: %v", c.name, err)
		}
		if got := len(v.Proposals) == 1; got != c.ok {
			t.Errorf("%s: proposed=%v, want %v (rejected: %v)", c.name, got, c.ok, v.Rejected)
		}
		if got := len(v.Kept) == 1; got != c.kept {
			t.Errorf("%s: kept=%v, want %v", c.name, got, c.kept)
		}
		if c.why != "" && !strings.Contains(strings.Join(v.Rejected, "\n"), c.why) {
			t.Errorf("%s: rejected %v, want a mention of %q", c.name, v.Rejected, c.why)
		}
		if c.ok {
			p := v.Proposals[0]
			if g := want[p.Path]; p.SHA != g.SHA || p.Blob != g.Blob || p.Lines != g.Lines {
				t.Errorf("%s: the proposal does not carry the hashes of the file as it was read: %+v", c.name, p)
			}
		}
	}
	// The same path twice: the second is dropped.
	v, _ := validateGhosts(fx.repo, ghostJSON(ghostItem("cmd/a.go", "describe", goodText), ghostItem("cmd/a.go", "describe", goodText+" Zwei.")), pkg, read("cmd/a.go"))
	if len(v.Proposals) != 1 || len(v.Rejected) != 1 {
		t.Errorf("a path named twice: %d proposals, rejected %v", len(v.Proposals), v.Rejected)
	}
	for _, in := range []string{"", "fertig", `{"verdicts":[]}`, "{kaputt"} {
		if _, err := validateGhosts(fx.repo, in, pkg, nil); err == nil {
			t.Errorf("%q accepted as the answer of a description session", in)
		}
	}
}

func TestGhostAnswerIsDroppedWhenTheFileChangedWhileTheSessionRead(t *testing.T) {
	fx := newGhostFixture(t)
	pkg, _ := SelectGhosts(fx.repo, fx.described, nil, nil, nil, 0)
	writeIn(t, fx.dir, "cmd/a.go", numbered("a", 4)+"// verändert\n")
	v, err := validateGhosts(fx.repo, ghostJSON(ghostItem("cmd/a.go", "describe", goodText)), pkg, seenBy([]string{"cmd/a.go"}))
	if err != nil {
		t.Fatal(err)
	}
	if len(v.Proposals) != 0 || !strings.Contains(strings.Join(v.Rejected, "\n"), "seit dem Lesen verändert") {
		t.Errorf("proposals=%d rejected=%v", len(v.Proposals), v.Rejected)
	}
	if err := os.Remove(filepath.Join(fx.dir, "cmd/a.go")); err != nil {
		t.Fatal(err)
	}
	if v, _ := validateGhosts(fx.repo, ghostJSON(ghostItem("cmd/a.go", "describe", goodText)), pkg, seenBy([]string{"cmd/a.go"})); len(v.Proposals) != 0 {
		t.Error("a file that is gone got a description")
	}
}

func TestGhostNoteCarriesTheTextAndTheHashesItWasWrittenFor(t *testing.T) {
	g := GhostProposalData{GhostPath: GhostPath{Path: "internal/store/x.go", State: GhostStale, Percent: 42, Old: oldText,
		SHA: strings.Repeat("a", 64), Blob: strings.Repeat("b", 40), Lines: 120},
		Description: "Erste Zeile.\n\nBegründung: das steht im Text, nicht im Kopf.\nBeschreibung:\nauch das.", Reason: "es hat sich geändert"}
	k := GhostProposal("github.com/o/r", g)
	if k.Harness != "gardener" || k.Confidence != "staged" || k.Status != "active" || k.SessionRef != "gardener:ghost:internal/store/x.go" || k.Title != "[Gärtner] Beschreibung? internal/store/x.go" {
		t.Errorf("note = %+v", k)
	}
	if got := ghostStand(k.Body); got != g.Blob {
		t.Errorf("stand = %q", got)
	}
	head, text, ok := strings.Cut(k.Body, ghostBodyMarker)
	if !ok || strings.TrimSpace(text) != g.Description {
		t.Errorf("the text after the marker is %q", text)
	}
	if !strings.Contains(head, "Bisher: "+store.GhostDescriptionHash(oldText)) || !strings.Contains(head, "sha="+g.SHA+" blob="+g.Blob+" zeilen=120") {
		t.Errorf("header:\n%s", head)
	}
	g.Old = ""
	if !strings.Contains(GhostProposal("p", g).Body, "Bisher: keine\n") {
		t.Error("no earlier description is not said")
	}
}

